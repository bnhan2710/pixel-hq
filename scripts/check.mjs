import { readFileSync, existsSync } from "node:fs";
import { join, basename, dirname, extname } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tracked = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
const failures = [];
const fail = (file, message) => failures.push(`${file}: ${message}`);
const read = (file) => readFileSync(join(root, file), "utf8");
const ofType = (...types) => tracked.filter((file) => types.includes(extname(file)));

const HERDR_MODS = new Set([
  "agents", "changes", "confirm", "files", "help", "machine-add", "menu", "new-menu", "pane", "peek", "picker",
  "prompt", "spaces", "tabs", "terminals-bar", "terminals-pane", "toast", "workspace-chrome", "workspace-status", "worktree",
]);
const GENERATED = new Set(["gpui-kit.d.ts", "herdr.d.ts", "jsconfig.json"]);
const repoMods = new Set(tracked.filter((file) => /^mods\/[^/]+\/main\.js$/.test(file)).map((file) => file.split("/")[1]));

for (const file of ofType(".js", ".mjs")) {
  try {
    execFileSync(process.execPath, ["--input-type=module", "--check"], { input: read(file), stdio: "pipe" });
  } catch (error) {
    fail(file, `syntax error\n${String(error.stderr).split("\n").slice(0, 4).join("\n").replace("[stdin]", file)}`);
  }
}

const json = {};
for (const file of ofType(".json")) {
  try {
    json[file] = JSON.parse(read(file));
  } catch (error) {
    fail(file, `invalid JSON: ${error.message}`);
  }
}

for (const file of ofType(".svg")) {
  const svg = read(file).trim();
  if (!/^(<\?xml[^>]*>\s*)?<svg[\s>]/.test(svg) || !svg.endsWith("</svg>")) fail(file, "not a single <svg> document");
}

for (const file of ofType(".js", ".mjs", ".json", ".md", ".svg", ".yml")) {
  const line = read(file).split("\n").findIndex((text) => /^(<{7}|>{7})( |$)|^={7}$/.test(text));
  if (line !== -1) fail(file, `merge conflict marker on line ${line + 1}`);
}

for (const file of tracked) {
  if (GENERATED.has(basename(file))) fail(file, "generated by herdr-app check; don't commit it");
}

for (const mod of repoMods) {
  if (!tracked.includes(`mods/${mod}/mod.json`)) fail(`mods/${mod}`, "has main.js but no mod.json");
}

for (const file of ofType(".js")) {
  if (!file.startsWith("mods/")) continue;
  for (const [, mod, path] of read(file).matchAll(/["'`]mods\/([\w-]+)\/([\w./-]+)["'`]/g)) {
    if (repoMods.has(mod) && !existsSync(join(root, "mods", mod, path))) fail(file, `references mods/${mod}/${path}, which isn't in the repo`);
  }
}

const modsIn = (node) => [
  ...(node?.content?.mod ? [node.content.mod] : []),
  ...(Array.isArray(node?.children) ? node.children.flatMap(modsIn) : []),
];
for (const file of tracked.filter((name) => /^layouts\/[^/]+\.json$/.test(name))) {
  const layout = json[file];
  if (!layout) continue;
  for (const mod of new Set(modsIn(layout))) {
    if (!repoMods.has(mod) && !HERDR_MODS.has(mod)) fail(file, `uses mod "${mod}", which is neither in mods/ nor shipped with Herdr`);
  }
  if (layout.theme && !tracked.includes(`themes/${layout.theme}.json`)) fail(file, `uses theme "${layout.theme}", but themes/${layout.theme}.json is missing`);
}

if (failures.length) {
  console.error(`${failures.length} problem${failures.length === 1 ? "" : "s"}:\n`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
console.log(`All checks passed (${tracked.length} files, ${repoMods.size} mods).`);
